import { randomBytes } from "node:crypto";
import { chmod, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve, sep } from "node:path";
import { passphraseProblem } from "./passphrase.js";
import type { Plan } from "./plan.js";
import { secretSourceRel, shellQuote, stepArgv } from "./shell.js";

export interface RenderOptions {
  /** Person names whose password is regenerated, or "all". Plan.rotate is always honoured too. */
  rotate?: string[] | "all";
  /** Chosen passphrases by person name. Written as that person's secret in place of a random one, and kept by later renders. */
  passwords?: Record<string, string>;
  /** Injected for tests. Default: crypto.randomBytes. */
  randomBytes?: (n: number) => Buffer;
}

export interface RenderResult {
  outDir: string;
  /** People for whom a new password was generated. */
  generated: string[];
  /** People whose existing password was kept. */
  kept: string[];
}

function inside(root: string, p: string): string {
  const full = resolve(root, p);
  if (full !== root && !full.startsWith(root + sep)) throw new Error(`refusing to write outside the output directory: ${p}`);
  return full;
}

async function writePrivate(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true, mode: 0o700 });
  await writeFile(path, content, { mode: 0o600 });
  await chmod(path, 0o600);
}


export function renderApplyScript(plan: Plan): string {
  const lines = [
    "#!/usr/bin/env bash",
    "# Generated by paseo-ctl. NOT executable on purpose. Read every line, then run it by hand:",
    "#   PASEO_CTL_I_REVIEWED=1 bash apply.sh user      # as your normal user (never as root)",
    "#   sudo env PASEO_CTL_I_REVIEWED=1 bash apply.sh root   # only if the plan has privileged steps",
    "# It changes the host. It contains no passwords: it copies them from secrets/.",
    "set -euo pipefail",
    'if [ "${PASEO_CTL_I_REVIEWED:-}" != "1" ]; then echo "refusing: read this script, then set PASEO_CTL_I_REVIEWED=1" >&2; exit 1; fi',
    'phase="${1:-}"',
    'case "$phase" in user) [ "$(id -u)" -ne 0 ] || { echo "phase user must not run as root" >&2; exit 1; } ;;',
    '  root) [ "$(id -u)" -eq 0 ] || { echo "phase root must run as root" >&2; exit 1; } ;;',
    '  *) echo "usage: apply.sh user|root" >&2; exit 1 ;; esac',
    'cd "$(dirname "$0")"',
    "",
  ];
  for (const s of plan.steps) {
    const phase = s.privileged ? "root" : "user";
    lines.push(`# ${s.id}: ${s.description}`);
    const argv = stepArgv(s);
    if (!argv) {
      lines.push(`# (manual, not run by this script)`, "");
      continue;
    }
    lines.push(`if [ "$phase" = ${phase} ]; then ${argv.map(shellQuote).join(" ")}; fi`, "");
  }
  lines.push("# Checks to run by hand afterwards (not run by this script):");
  for (const s of plan.verify) {
    const argv = stepArgv(s);
    lines.push(`#   ${s.id}: ${s.description}${argv ? `\n#     ${argv.map(shellQuote).join(" ")}` : ""}`);
  }
  lines.push("");
  return lines.join("\n");
}

/**
 * Write the plan into outDir (and only there). Passwords are generated here, never earlier, and only ever land in
 * secrets/. An existing password is kept unless rotation is requested.
 */
export async function renderPlan(plan: Plan, outDirInput: string, opts: RenderOptions = {}): Promise<RenderResult> {
  const outDir = resolve(outDirInput);
  if (outDir === sep) throw new Error("refusing to render into /");
  const rng = opts.randomBytes ?? randomBytes;

  // Only reuse a directory that is empty or was rendered by this tool; we delete files/ inside it.
  try {
    const entries = await readdir(outDir);
    if (entries.length > 0 && !entries.includes("plan.json")) {
      throw new Error(`${outDir} is not empty and has no plan.json; pick an empty output directory`);
    }
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code !== "ENOENT") throw e;
  }
  await mkdir(outDir, { recursive: true });

  const filesRoot = inside(outDir, "files");
  await rm(filesRoot, { recursive: true, force: true });
  for (const s of plan.steps) {
    if (s.kind === "file" && s.file?.content !== undefined) {
      const target = inside(filesRoot, s.file.path.replace(/^\/+/, ""));
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, s.file.content, { mode: 0o644 });
      await chmod(target, 0o644);
    }
  }

  const generated: string[] = [];
  const kept: string[] = [];
  const secretNames = [...new Set(plan.steps.flatMap((s) => (s.file?.secretRef ? [s.file.secretRef] : [])))];
  if (secretNames.length > 0) {
    const secretsDir = inside(outDir, "secrets");
    await mkdir(secretsDir, { recursive: true, mode: 0o700 });
    await chmod(secretsDir, 0o700);
    for (const name of secretNames) {
      const pwPath = inside(outDir, `secrets/${name}.password`);
      const rotate = plan.rotate.includes(name) || opts.rotate === "all" || (Array.isArray(opts.rotate) && opts.rotate.includes(name));
      let password: string | undefined;
      const chosen = opts.passwords?.[name];
      if (chosen !== undefined) {
        const problem = passphraseProblem(chosen, name);
        if (problem) throw new Error(`${name}: ${problem}`);
        password = chosen;
        generated.push(name);
      } else {
        if (!rotate) {
          const existing = await readFile(pwPath, "utf8").catch(() => undefined);
          if (existing !== undefined && passphraseProblem(existing.trim()) === undefined) password = existing.trim();
        }
        if (password === undefined) {
          password = rng(32).toString("base64url");
          generated.push(name);
        } else {
          kept.push(name);
        }
      }
      await writePrivate(pwPath, `${password}\n`);
      await writePrivate(inside(outDir, secretSourceRel(name)), `PASEO_PASSWORD=${password}\n`);
    }
  }

  // plan.json: steps with content are fine (units hold no secrets); secret files carry only a reference.
  await writeFile(inside(outDir, "plan.json"), `${JSON.stringify(plan, null, 2)}\n`, { mode: 0o644 });
  const script = inside(outDir, "apply.sh");
  await writeFile(script, renderApplyScript(plan), { mode: 0o644 });
  await chmod(script, 0o644);
  return { outDir, generated, kept };
}
